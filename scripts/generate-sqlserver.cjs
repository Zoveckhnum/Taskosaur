// The PostgreSQL schema remains the application type contract. SQL Server stores
// JSON/lists as NVARCHAR(MAX); sqlserver.extension.ts translates at the boundary.
const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../backend/prisma/schema.prisma'), 'utf8').replace(/\r\n/g, '\n');
const enums = new Map([...source.matchAll(/enum (\w+) \{([\s\S]*?)\n\}/g)].map(m => [m[1], [...m[2].matchAll(/^\s*(\w+)\s*(?:\/\/.*)?$/gm)].map(v => v[1])]));
let schema = source.replace(/enum \w+ \{[\s\S]*?\n\}/g, '')
  .replace('provider = "prisma-client-js"', 'provider = "prisma-client-js"\n  output = "../../generated/sqlserver"')
  .replace('provider = "postgresql"', 'provider = "sqlserver"\n  relationMode = "prisma"')
  .replace(/@db\.Uuid/g, '@db.UniqueIdentifier').replace(/@db\.Text/g, '@db.NVarChar(Max)');
schema = schema.split('\n').map(line => {
  const match = line.match(/^(\s+\w+\s+)(\w+)(\?|\[\])?(.*)$/);
  if (!match) return line;
  const [, prefix, type, suffix = '', rest] = match;
  if (type === 'Json' || suffix === '[]' && ['String', 'Int'].includes(type)) {
    return prefix + 'String' + (suffix === '?' ? '?' : '') + rest + ' @db.NVarChar(Max)' + (suffix === '[]' ? ' @default("[]")' : '');
  }
  if (enums.has(type)) return prefix + 'String' + suffix + rest.replace(/@default\((\w+)\)/g, '@default("$1")') + ' @db.NVarChar(64)';
  return line;
}).join('\n');
// Comments must follow attributes, never swallow generated native types.
schema = schema.replace(/(\/\/[^\n]*?)( @db\.NVarChar\(Max\)(?: @default\("\[\]"\))?| @db\.NVarChar\(64\))/g, '$2 $1');
// IDs never change. Break optional/self cycles while preserving ownership cascades.
schema = schema.replace(/@relation\(([^\n]*fields:[^\n]*)\)/g, (whole, args) => {
  args = args.replace(/,?\s*onUpdate:\s*\w+/g, '');
  if (!/onDelete: Cascade/.test(args)) args = args.replace(/,?\s*onDelete:\s*\w+/g, '') + ', onDelete: NoAction';
  return '@relation(' + args + ', onUpdate: NoAction)';
});
schema = schema.replace(/model (\w+) \{([\s\S]*?)\n\}/g, (whole, name, body) => {
  const indexed = new Set([...body.matchAll(/@@(?:index|unique)\(\[([^\]]+)\]/g)].flatMap(m => m[1].split(',').map(s => s.trim())));
  for (const match of body.matchAll(/^\s*(\w+)\s+String\??[^\n]*@unique/gm)) indexed.add(match[1]);
  body = body.split('\n').map(line => {
    const field = line.match(/^\s*(\w+)\s+String\??\s/);
    if (field && indexed.has(field[1]) && !line.includes('@db.')) return line.replace(/(\s*\/\/.*)?$/, ' @db.NVarChar(255)$1');
    return line;
  }).join('\n');
  const extra = [...body.matchAll(/fields: \[([^\]]+)\]/g)].map(m => m[1]).filter(fields => !new RegExp('@@(?:index|unique)\\(\\[' + fields.split(',')[0].trim() + '(?:,|\\])').test(body));
  for (const fields of new Set(extra)) body += '\n  @@index([' + fields + '])';
  return 'model ' + name + ' {' + body + '\n}';
});
fs.mkdirSync(path.join(__dirname, '../backend/prisma/sqlserver'), { recursive: true });
fs.writeFileSync(path.join(__dirname, '../backend/prisma/sqlserver/schema.prisma'), '// Generated by scripts/generate-sqlserver.cjs. Do not edit.\n' + schema);
